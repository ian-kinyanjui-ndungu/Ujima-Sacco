# --- TEST 5: TELEMETRY ANOMALY DETECTION ---
def test_telemetry_anomaly_detection():
    """
    Verify that if the approval rate drops by more than 30% in a sub-county,
    a system-wide flag is triggered.
    """
    sub_county = "Busia Central"
    
    # Baseline for Busia Central is initialized as 8 approvals in 10 tests (80%).
    # We record 5 consecutive denials to drop recent rate to 0%.
    # Drop: (0.80 - 0.0) / 0.80 = 100% drop, which is > 30% threshold.
    
    for _ in range(5):
        record_and_analyze_telemetry(sub_county, approved=False)
        
    alerts = get_anomaly_alerts()
    assert len(alerts) > 0
    assert any("Busia Central" in alert for alert in alerts)
    assert any("dropped" in alert for alert in alerts)


# --- TEST 6: DATA SOVEREIGNTY CHECKS ---
def test_data_sovereignty_checks():
    """
    Ensure S3/DB configs targeting foreign regions throw connection exceptions.
    """
    # af-south-1 (local African zone) should pass
    local_uri = "s3://ujima-bucket.s3.af-south-1.amazonaws.com"
    assert verify_data_residency(local_uri) is True
    
    # us-east-1 (foreign region) should fail
    foreign_uri = "s3://ujima-bucket.s3.us-east-1.amazonaws.com"
    with pytest.raises(ConnectionError) as excinfo:
        verify_data_residency(foreign_uri)
    assert "DATA SOVEREIGNTY VIOLATION" in str(excinfo.value)


# --- TEST 7: USSD RUNTIME COMMANDS ---
def test_ussd_runtime_commands():
    """
    Verify that commands *#700# (pause) and *#733# (takeover) execute correctly.
    """
    profile = db.get_profile("member_busia_shea")
    state = StateThread(member_id="member_busia_shea")
    
    # 1. Trigger Pause Command
    state, resp = process_ussd_sms_loop(state, profile, "*#700#")
    assert state.paused is True
    assert "PAUSED" in resp
    
    # Any incoming message while paused should return a pause reminder
    state, resp = process_ussd_sms_loop(state, profile, "hello")
    assert "currently paused" in resp
    
    # Unpause
    state, resp = process_ussd_sms_loop(state, profile, "*#700#")
    assert state.paused is False
    assert "RESUMED" in resp
    
    # 2. Trigger Takeover Command *#733#
    state, resp = process_ussd_sms_loop(state, profile, "*#733#")
    assert state.current_agent == "hunter"
    assert state.human_escalation_status == "pending_review"
    assert "prioritized for human review" in resp
