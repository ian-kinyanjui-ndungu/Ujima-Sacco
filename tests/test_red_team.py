# --- TEST 1: RED TEAM SEASONAL VENDOR (Auma Nakami - Shea Butter Vendor) ---
def test_shea_butter_vendor_escalation():
    """
    Test that a 38-year-old shea butter vendor in Busia requesting KES 10,000
    under stress triggers automated handoff and is ESCALATED due to the vulnerability 
    matrix (2 children under age 5). It also verifies the specialist assignment (John).
    """
    # 1. Verify profile is loaded in mock db
    profile = db.get_profile("member_busia_shea")
    assert profile is not None
    assert profile.crop_type == "shea_butter"
    assert len(profile.estimated_child_ages) == 4
    
    # Check children under 5 (ages 3, 4)
    children_under_5 = sum(1 for age in profile.estimated_child_ages if age < 5)
    assert children_under_5 == 2
    
    # 2. Simulate inbound SMS indicating intense financial stress
    # Inbound message: "Drought killed my crops. Need KES 10000 for school fees."
    payload = {
        "member_id": "member_busia_shea",
        "text": "Drought killed my crops. Need KES 10000 for school fees.",
        "sub_county": "Busia Central"
    }
    
    response = client.post("/sms/inbound", json=payload)
    assert response.status_code == 200
    data = response.json()
    
    # 3. Check transition results
    state = db.get_state("member_busia_shea")
    
    # Scout should have handed off to Guardian, which should have escalated to Hunter
    assert state.current_agent == "hunter"
    assert state.human_escalation_status == "pending_review"
    assert "INTENSE_STRESS_DETECTED" in state.financial_stress_flags
    assert "MULTIPLE_UNDER_5_DEPENDENTS" in state.financial_stress_flags
    
    # 4. Check briefing packet generated by Hunter Agent
    briefing_packet = state.telemetry_metadata.get("briefing_packet")
    assert briefing_packet is not None
    assert "Human Loan Officer Briefing Packet" in briefing_packet
    assert "**Assigned Specialist:** John" in briefing_packet  # John is shea butter specialist
    assert "Busia Central" in briefing_packet
    assert "Shea_Butter" in briefing_packet
    
    # 5. Check response message content is empathetic and references officer John
    assert "John" in data["text"]
    assert "prioritized for human review" in data["text"]


def test_shea_butter_vendor_no_escalation_auto_approve():
    """
    If we modify the vendor's profile temporarily to have only 1 child under 5 (non-escalating household risk),
    and she requests a loan ≤ KES 15,000 aligned with crop peaks, it should auto-approve.
    """
    # Temporarily alter children ages to check triage logic
    profile = db.get_profile("member_busia_shea")
    profile.estimated_child_ages = [3, 6, 8, 12]  # Only 1 child under 5 (age 3)
    
    # Directly process the orchestrator state to test Guardian Triage
    state = StateThread(member_id="member_busia_shea", current_agent="guardian")
    
    # Repayment date check
    _, is_aligned = determine_repayment_date(datetime.now())
    
    # Run loop
    state, response_text = process_ussd_sms_loop(state, profile, "need loan of 12000")
    
    if is_aligned:
        assert state.loan_application.status == "approved"
        assert "approved" in response_text.lower()
    else:
        # If today is a non-peak alignment day
        assert state.loan_application.status == "denied"
        assert "unsuccessful" in response_text.lower() or "protective" in response_text.lower()


