# --- TEST 3: BIAS MITIGATION FILTER (PROXY VARIABLES) ---
def test_bias_mitigation_filter():
    """
    Verify that sensitive fields and traditional crop proxies (e.g. shea_butter, matooke)
    are scrubbed or flagged in the raw features list, appending alerts.
    """
    raw_data = {
        "gender": "female",
        "tribe": "Luhya",
        "crop_type": "shea_butter",
        "sub_county": "Busia Central"
    }
    
    scrubbed = scrub_sensitive_proxies(raw_data)
    
    # Explicit variables should be removed
    assert "gender" not in scrubbed
    assert "tribe" not in scrubbed
    
    # Crop proxy should be scrubbed
    assert scrubbed["crop_type"] == "[REDACTED_GENDER_PROXY]"
    
    # Alerts should record variables scrubbed
    alerts = scrubbed.get("_bias_mitigation_alerts", [])
    assert "gender" in alerts
    assert "tribe" in alerts
    assert "crop_type (gender proxy)" in alerts


